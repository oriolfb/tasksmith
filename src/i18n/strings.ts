const DICTS: Record<Locale, Dict> = { ca, es, en };

let currentLocale: Locale = detectLocale();

export function setLocale(locale: Locale): void {
  currentLocale = locale;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function t(key: string, params?: Record<string, string | number>): string {
  const template = DICTS[currentLocale][key] ?? DICTS.en[key] ?? key;
  if (!params) return template;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{{${name}}}`, String(value)),
    template,
  );
}

/** Picks `${key}.one` for count === 1, `${key}.other` otherwise, and interpolates `count` plus any extra params. */
export function tn(key: string, count: number, params?: Record<string, string | number>): string {
  const suffix = count === 1 ? "one" : "other";
  return t(`${key}.${suffix}`, { count, ...params });
}
